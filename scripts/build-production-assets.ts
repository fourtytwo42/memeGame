function dist(
  r: number,
  g: number,
  b: number,
  key: { r: number; g: number; b: number }
) {
  return Math.sqrt(
    (r - key.r) * (r - key.r) +
      (g - key.g) * (g - key.g) +
      (b - key.b) * (b - key.b)
  );
}

function alphaFor(distance: number) {
  if (distance <= 42) return 0;
  if (distance >= 110) return 255;
  return Math.round(((distance - 42) / 68) * 255);
}

function sampledKey(
  data: Buffer,
  width: number,
  height: number,
  fallback: { r: number; g: number; b: number }
) {
  const samples: Array<[number, number, number]> = [];
  const span = Math.min(24, Math.floor(width / 8), Math.floor(height / 8));
  const corners = [
    [0, 0],
    [width - span, 0],
    [0, height - span],
    [width - span, height - span]
  ];
  for (const [startX, startY] of corners) {
    for (let y = startY; y < startY + span; y++) {
      for (let x = startX; x < startX + span; x++) {
        const index = (y * width + x) * 4;
        samples.push([data[index], data[index + 1], data[index + 2]]);
      }
    }
  }
  if (samples.length === 0) return fallback;
  samples.sort(
    (a, b) =>
      dist(a[0], a[1], a[2], fallback) - dist(b[0], b[1], b[2], fallback)
  );
  const best = samples.slice(0, Math.max(1, Math.floor(samples.length * 0.7)));
  const total = best.reduce(
    (acc, sample) => {
      acc.r += sample[0];
      acc.g += sample[1];
      acc.b += sample[2];
      return acc;
    },
    { r: 0, g: 0, b: 0 }
  );
  return {
    r: Math.round(total.r / best.length),
    g: Math.round(total.g / best.length),
    b: Math.round(total.b / best.length)
  };
}

async function renderAsset(asset: CellAsset) {
  const sheet = sheets[asset.sheet];
  const sheetPath = path.join(root, sheet.source);
  const metadata = await sharp(sheetPath).metadata();
  if (!metadata.width || !metadata.height) {
    throw new Error(`Cannot read dimensions for ${sheet.source}`);
  }

  const cellWidth = Math.floor(metadata.width / sheet.cols);
  const cellHeight = Math.floor(metadata.height / sheet.rows);
  const left = asset.col * cellWidth;
  const top = asset.row * cellHeight;
  const extractWidth =
    asset.col === sheet.cols - 1 ? metadata.width - left : cellWidth;
  const extractHeight =
    asset.row === sheet.rows - 1 ? metadata.height - top : cellHeight;

  const { data, info } = await sharp(sheetPath)
    .extract({ left, top, width: extractWidth, height: extractHeight })
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });

  const actualKey = sampledKey(data, info.width, info.height, sheet.key);

  for (let i = 0; i < data.length; i += 4) {
    const distance = dist(data[i], data[i + 1], data[i + 2], actualKey);
    const alpha = Math.min(data[i + 3], alphaFor(distance));
    data[i + 3] = alpha;
    if (alpha < 255) {
      data[i] = Math.round(data[i] * (alpha / 255));
      data[i + 1] = Math.round(data[i + 1] * (alpha / 255));
      data[i + 2] = Math.round(data[i + 2] * (alpha / 255));
    }
  }

  let minX = info.width;
  let minY = info.height;
  let maxX = 0;
  let maxY = 0;
  for (let y = 0; y < info.height; y++) {
    for (let x = 0; x < info.width; x++) {
      const alpha = data[(y * info.width + x) * 4 + 3];
      if (alpha > 8) {
        minX = Math.min(minX, x);
        minY = Math.min(minY, y);
        maxX = Math.max(maxX, x);
        maxY = Math.max(maxY, y);
      }
    }
  }

  const output = path.join(root, asset.output);
  await mkdir(path.dirname(output), { recursive: true });

  const padding = asset.id === "share-foundry-workshop" ? 0 : 24;
  const crop =
    maxX > minX && maxY > minY
      ? (() => {
          const cropLeft = Math.max(0, minX - padding);
          const cropTop = Math.max(0, minY - padding);
          const cropRight = Math.min(info.width - 1, maxX + padding);
          const cropBottom = Math.min(info.height - 1, maxY + padding);
          return {
            left: cropLeft,
            top: cropTop,
            width: cropRight - cropLeft + 1,
            height: cropBottom - cropTop + 1
          };
        })()
      : { left: 0, top: 0, width: info.width, height: info.height };

  const width = asset.width ?? 512;
  const height = asset.height ?? 512;
  await sharp(data, {
    raw: {
      width: info.width,
      height: info.height,
      channels: 4
    }
  })
    .extract(crop)
    .resize(width, height, {
      fit: "contain",
      background: { r: 0, g: 0, b: 0, alpha: 0 }
    })
    .png({ compressionLevel: 9, adaptiveFiltering: true })
    .toFile(output);

  return {
    id: asset.id,
    category: asset.category,
    sourcePrompt: sheet.prompt,
    sourceImagePath: sheet.source,
    finalAssetPath: asset.output,
    keyColor: sheet.keyHex,
    backgroundRemovalMethod:
      "local sharp chroma-key removal with soft alpha matte",
    dimensions: { width, height },
    format: "png",
    usage: asset.usage,
    altText: asset.altText,
    status: "ready",
    reviewNotes: asset.reviewNotes,
    createdAt: today,
    updatedAt: today
  };
}

async function main() {
  const manifestPath = path.join(root, "assets/manifest/assets.json");
  const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
  const generated = [];
  for (const asset of assets) {
    generated.push(await renderAsset(asset));
  }

  const preserved = manifest.assets.filter(
    (entry: { id: string }) => !generated.some((asset) => asset.id === entry.id)
  );
  manifest.assets = [...preserved, ...generated].sort(
    (a: { id: string }, b: { id: string }) => a.id.localeCompare(b.id)
  );
  await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
  console.log(
    JSON.stringify(
      {
        generatedAssets: generated.length,
        finalAssetRoot: manifest.workflow.finalAssetRoot
      },
      null,
      2
    )
  );
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
